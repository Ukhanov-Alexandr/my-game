/**
 * Все уровни по порядку. Каждый — обычный уровень { width, height, cells }
 * с дополнительными полями:
 *   id   — номер уровня, начиная с 1;
 *   name — название;
 *   hint — подсказка для первых уровней (может отсутствовать).
 */
export const levels = MAPS.map(({ name, hint, map }, i) => ({
  id: i + 1,
  name,
  ...(hint ? { hint } : {}),
  ...parseLevel(map),
}));

/** Уровень по номеру (id) или null. */
export function getLevel(id) {
  return levels.find((level) => level.id === id) ?? null;
}
